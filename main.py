"""Command-line entry point for the hybrid multi-agent runtime."""

from __future__ import annotations

import argparse
import sqlite3
import sys
import uuid
from pathlib import Path
from typing import Any

from core.config import PACKAGE_ROOT, load_settings
from core.engine import build_graph
from core.events import CompositeEventSink, ConsoleEventSink, SQLiteEventSink
from core.state import AgentGraphState
from tools.bash_tools import run_command


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run a task through the multi-agent workflow")
    parser.add_argument("--project-dir", help="Target project directory")
    parser.add_argument("--task", help="Task for the agents to implement")
    parser.add_argument("--settings", help="Optional settings YAML path")
    parser.add_argument("--thread-id", help="Checkpoint thread id (generated by default)")
    parser.add_argument("--run-id", help="Stable run id (generated by default)")
    parser.add_argument("--max-parallel", type=int, help="Maximum parallel local workers")
    parser.add_argument("--verbose", action="store_true", help="Show tool-level live events")
    parser.add_argument("--event-db", help="SQLite audit log path")
    parser.add_argument("--resume", help="Resume a checkpointed run/thread id")
    return parser.parse_args(argv)


def initial_state(
    project_root: str, task: str, settings: dict[str, Any], run_id: str | None = None
) -> AgentGraphState:
    max_retries = int(settings.get("system", {}).get("max_retries_per_task", 3))
    return {
        "run_id": run_id or str(uuid.uuid4()),
        "project_root": project_root,
        "user_prompt": task,
        "project_context": "",
        "plan": [],
        "max_retries": max_retries,
        "artifacts": [],
        "worker_results": {},
        "scheduled_task_ids": [],
        "workspace": {},
        "task_workspaces": {},
        "is_completed": False,
        "final_summary": "",
        "review_retry_count": 0,
        "replan_count": 0,
        "settings": settings,
    }


def print_report(result: AgentGraphState) -> None:
    print("\n=== Execution report ===")
    for task in result["plan"]:
        print(f"[{task.status.upper():11}] #{task.id} {task.description}")
    changed: list[str] = []
    for artifact in result["artifacts"]:
        changed.extend(artifact.files_created)
        changed.extend(artifact.files_modified)
    if changed:
        print("\nFiles touched:")
        for path in dict.fromkeys(changed):
            print(f"  - {path}")
    status = run_command(result["project_root"], "git status --short")
    diff = run_command(result["project_root"], "git diff --no-ext-diff")
    if status["exit_code"] == 0 and status["stdout"].strip():
        print("\nGit status:")
        print(status["stdout"].rstrip())
    if diff["exit_code"] == 0 and diff["stdout"].strip():
        print("\nGit diff:")
        print(diff["stdout"].rstrip())
    print(f"\n{result['final_summary']}")


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    if not args.resume and (not args.project_dir or not args.task):
        print("error: --project-dir and --task are required for a new run", file=sys.stderr)
        return 2
    project_root = Path(args.project_dir).expanduser().resolve() if args.project_dir else None
    if project_root is not None and not project_root.is_dir():
        print(f"error: project directory does not exist: {project_root}", file=sys.stderr)
        return 2
    try:
        settings = load_settings(args.settings)
        if args.max_parallel:
            if args.max_parallel < 1:
                raise ValueError("--max-parallel must be positive")
            settings.setdefault("scheduler", {})["max_parallel_tasks"] = args.max_parallel
        run_id = args.resume or args.run_id or str(uuid.uuid4())
        database = Path(args.event_db) if args.event_db else PACKAGE_ROOT / settings["system"]["database_path"]
        sink = CompositeEventSink(ConsoleEventSink(args.verbose), SQLiteEventSink(database))
        try:
            from langgraph.checkpoint.sqlite import SqliteSaver
        except ImportError as exc:
            raise RuntimeError("Install dependencies again: pip install -r requirements.txt") from exc
        checkpoint_db = sqlite3.connect(database, check_same_thread=False)
        graph = build_graph(
            settings, event_sink=sink, checkpointer=SqliteSaver(checkpoint_db)
        )
        state = (
            initial_state(str(project_root), args.task, settings, run_id)
            if not args.resume else None
        )
        config = {
            "configurable": {"thread_id": args.thread_id or run_id},
            "recursion_limit": max(
                50, (((state or {}).get("max_retries", 3)) + 2) * 20
            ),
        }
        result: AgentGraphState = (
            state if state is not None else graph.get_state(config).values
        )
        if not result:
            raise ValueError(f"No checkpoint found for run: {run_id}")
        for snapshot in graph.stream(
            state, config=config, stream_mode="values"
        ):
            result = snapshot
        print_report(result)
        print(f"\nRun ID: {run_id}\nAudit DB: {database}")
        checkpoint_db.close()
        return 0 if result["is_completed"] else 1
    except KeyboardInterrupt:
        print("Interrupted", file=sys.stderr)
        return 130
    except Exception as exc:
        print(f"error: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())

