"""Command-line entry point for the hybrid multi-agent runtime."""

from __future__ import annotations

import argparse
import sys
import uuid
from pathlib import Path
from typing import Any

from core.config import load_settings
from core.engine import build_graph
from core.state import AgentGraphState
from tools.bash_tools import run_command


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run a task through the multi-agent workflow")
    parser.add_argument("--project-dir", required=True, help="Target project directory")
    parser.add_argument("--task", required=True, help="Task for the agents to implement")
    parser.add_argument("--settings", help="Optional settings YAML path")
    parser.add_argument("--thread-id", help="Checkpoint thread id (generated by default)")
    return parser.parse_args(argv)


def initial_state(project_root: str, task: str, settings: dict[str, Any]) -> AgentGraphState:
    max_retries = int(settings.get("system", {}).get("max_retries_per_task", 3))
    return {
        "project_root": project_root,
        "user_prompt": task,
        "project_context": "",
        "plan": [],
        "current_task_index": 0,
        "retry_count": 0,
        "max_retries": max_retries,
        "artifacts": [],
        "is_completed": False,
        "final_summary": "",
        "review_retry_count": 0,
        "settings": settings,
    }


def print_report(result: AgentGraphState) -> None:
    print("\n=== Execution report ===")
    for task in result["plan"]:
        print(f"[{task.status.upper():11}] #{task.id} {task.description}")
    changed: list[str] = []
    for artifact in result["artifacts"]:
        changed.extend(artifact.files_created)
        changed.extend(artifact.files_modified)
    if changed:
        print("\nFiles touched:")
        for path in dict.fromkeys(changed):
            print(f"  - {path}")
    status = run_command(result["project_root"], "git status --short")
    diff = run_command(result["project_root"], "git diff --no-ext-diff")
    if status["exit_code"] == 0 and status["stdout"].strip():
        print("\nGit status:")
        print(status["stdout"].rstrip())
    if diff["exit_code"] == 0 and diff["stdout"].strip():
        print("\nGit diff:")
        print(diff["stdout"].rstrip())
    print(f"\n{result['final_summary']}")


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    project_root = Path(args.project_dir).expanduser().resolve()
    if not project_root.is_dir():
        print(f"error: project directory does not exist: {project_root}", file=sys.stderr)
        return 2
    try:
        settings = load_settings(args.settings)
        graph = build_graph(settings)
        state = initial_state(str(project_root), args.task, settings)
        result = graph.invoke(
            state,
            config={
                "configurable": {"thread_id": args.thread_id or str(uuid.uuid4())},
                "recursion_limit": max(25, (state["max_retries"] + 2) * 10),
            },
        )
        print_report(result)
        return 0 if result["is_completed"] else 1
    except KeyboardInterrupt:
        print("Interrupted", file=sys.stderr)
        return 130
    except Exception as exc:
        print(f"error: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())

